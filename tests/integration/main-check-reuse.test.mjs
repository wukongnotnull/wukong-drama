import { writeModelShot } from '../fixtures/model.mjs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { render } from '../../plugin/engine/core/job.mjs';
import { snapshotMain, checkMainUnchanged } from '../../plugin/engine/core/approval.mjs';
import { recordApproval } from '../../plugin/engine/core/state.mjs';

process.env.WKD_NO_FONT_DOWNLOAD = '1';
process.env.WKD_WORKERS = '2';
for (const style of ['ink-wash', 'anime']) test(`${style} 主版证明复用，缺失快照、片段替换与镜头集合变化失效`, async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wkd-main-proof-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  fs.mkdirSync(path.join(dir, 'shots'));
  const ext='json';
  const file = path.join(dir, 'shots', `s01.${ext}`);
  const source=JSON.stringify(writeModelShot(file,{color:'white'}));
  fs.writeFileSync(file, source);
  const film = { title: 'proof', style, size: [160,90], fps: 10, seed: 1, generation: {image:{provider:"openai"},video:{provider:"seedance"}},cues:{pulse:[0,0.2]}, variants: { '9:16': {} }, shots: [{id:'s01',file:`shots/s01.${ext}`,duration:0.4}] };
  fs.writeFileSync(path.join(dir,'film.json'), JSON.stringify(film));
  await render(dir,{log:()=>{}});
  recordApproval(dir,{main:snapshotMain(dir,{log:()=>{}}).hashes});
  fs.writeFileSync(file,JSON.stringify({...JSON.parse(source),revision:'changed'}));
  const a=await checkMainUnchanged(dir,{aspect:'9:16',log:()=>{}});
  assert.equal(a.ok,true); assert.equal(a.reused,false);
  const logs=[];
  const b=await checkMainUnchanged(dir,{aspect:'9:16',log:s=>logs.push(s)});
  assert.equal(b.reused,true); assert.equal(b.verifiedAt,a.verifiedAt);
  assert.ok(!logs.some(s=>/缓存命中|渲染.*镜头用时/.test(s)), '证明命中不调用主版渲染');
  fs.writeFileSync(file,JSON.stringify({...JSON.parse(source),revision:'another-reference'}));
  assert.equal((await checkMainUnchanged(dir,{aspect:'9:16',log:()=>{}})).reused,false,'参考修订变化重新测量');
  const beforeManifest=fs.readFileSync(path.join(dir,'.cache/manifest.json'));
  for(const settings of [{fps:20},{size:[320,180]}]){
    fs.writeFileSync(path.join(dir,'film.json'),JSON.stringify({...film,...settings}));
    const changed=await checkMainUnchanged(dir,{aspect:'9:16',log:()=>{}});
    assert.equal(changed.ok,false);assert.equal(changed.timingChanged,true);
    assert.deepEqual(fs.readFileSync(path.join(dir,'.cache/manifest.json')),beforeManifest,'旧定稿条件变化不自动重渲');
  }
  fs.writeFileSync(path.join(dir,'film.json'),JSON.stringify(film));
  const manifest=JSON.parse(fs.readFileSync(path.join(dir,'.cache/manifest.json')));
  const segment=manifest.shots.s01.file,segmentBytes=fs.readFileSync(segment);
  const replacement=path.join(dir,'replacement.mp4');
  const made=spawnSync('ffmpeg',['-v','error','-f','lavfi','-i','color=c=black:s=160x90:r=10:d=0.4','-pix_fmt','yuv420p','-y',replacement]);
  assert.equal(made.status,0);
  fs.copyFileSync(replacement,segment);
  const bad=await checkMainUnchanged(dir,{aspect:'9:16',log:()=>{}});
  assert.equal(bad.ok,false);assert.equal(bad.reused,false,'同路径有效视频被替换不能沿用证明');
  fs.writeFileSync(segment,segmentBytes);
  const snap=path.join(dir,'.cache/approved/s01.mp4'), original=fs.readFileSync(snap);
  fs.rmSync(snap);
  assert.equal((await checkMainUnchanged(dir,{aspect:'9:16',log:()=>{}})).ok,false);
  fs.writeFileSync(snap,original);
  const approved = JSON.parse(fs.readFileSync(path.join(dir,'.wkd/state.json'))).approved.main;
  recordApproval(dir,{main:approved});
  assert.equal((await checkMainUnchanged(dir,{aspect:'9:16',log:()=>{}})).reused,false,'重新签批即使哈希相同也失效');
  film.shots=[];
  film.shots.push({id:'s02',file:`shots/s01.${ext}`,duration:0.4});
  fs.writeFileSync(path.join(dir,'film.json'), JSON.stringify(film));
  const changed=await checkMainUnchanged(dir,{aspect:'9:16',log:()=>{}});
  assert.equal(changed.ok,false); assert.ok(changed.rows.some(r=>r.id==='s01'&&r.result==='fail'));
});
